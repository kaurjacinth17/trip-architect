// Link the curated places in destinations.raw.ts to Google place IDs, storing IDs only.
//
//   GOOGLE_PLACES_SERVER_KEY=… node scripts/link-curated.ts            (Node 22.18+ runs TypeScript directly)
//   GOOGLE_PLACES_SERVER_KEY=… node scripts/link-curated.ts --dry-run  (prints, writes nothing)
//
// Uses Text Search with the field mask `places.id`, which Google bills as "Text Search Essentials (IDs Only)":
// free and unlimited. Each query is the curated name + destination, biased to the curated coordinates; the first
// result is taken only if Google returns exactly one or the curated name appears in the query. Review the output
// diff before committing: a wrong match links the wrong Google listing.
import fs from 'node:fs';
import path from 'node:path';
import { DESTS } from '../src/data/destinations.raw.ts';

const key = process.env.GOOGLE_PLACES_SERVER_KEY;
if (!key) { console.error('Set GOOGLE_PLACES_SERVER_KEY'); process.exit(1); }
const dry = process.argv.includes('--dry-run');
const out = path.resolve(import.meta.dirname, '../src/data/curatedPlaceIds.ts');

async function find(text: string, lat: number, lng: number): Promise<string[]> {
  const r = await fetch('https://places.googleapis.com/v1/places:searchText', {
    method: 'POST',
    headers: { 'content-type': 'application/json', 'X-Goog-Api-Key': key!, 'X-Goog-FieldMask': 'places.id' },
    body: JSON.stringify({ textQuery: text, pageSize: 3, locationBias: { circle: { center: { latitude: lat, longitude: lng }, radius: 3000 } } }),
  });
  if (!r.ok) throw new Error(`Google ${r.status}`);
  const b = (await r.json()) as { places?: { id: string }[] };
  return (b.places || []).map((p) => p.id);
}

const ids: Record<string, string> = {};
let miss = 0;
for (const d of DESTS) {
  for (const p of d.places) {
    const pid = `${d.id}:${p[0]}`;
    try {
      const found = await find(`${p[1]}, ${d.name}`, p[4], p[5]);
      if (found[0]) ids[pid] = found[0];
      else miss++;
      console.log(found[0] ? '✓' : '✗', pid, found[0] || '');
    } catch (e) {
      console.error('error', pid, (e as Error).message);
      miss++;
    }
    await new Promise((res) => setTimeout(res, 120));
  }
}
const body = `// Curated place → Google place ID (IDs only; generated by scripts/link-curated.ts, reviewed by hand).\n// Place IDs may be stored indefinitely under the Google Maps Platform terms. Re-run occasionally: IDs can change.\nexport const CURATED_PLACE_IDS: Record<string, string> = ${JSON.stringify(ids, null, 2)};\n`;
console.log(`${Object.keys(ids).length} linked, ${miss} not found`);
if (!dry) fs.writeFileSync(out, body);
